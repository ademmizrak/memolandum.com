import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const OUT_DIR = path.join(ROOT, "out");
const ANDROID_PUBLIC_DIR = path.join(ROOT, "android", "app", "src", "main", "assets", "public");

// Folders/files to strictly EXCLUDE from the mobile APK/AAB bundle
// All of these are fetched on-demand from Google Cloud Storage / CDN
const EXCLUDE_NAMES = new Set([
  "data",             // Lesson datasets -> GCS CDN
  "sozluk",           // 4000+ SSG dictionary pages -> Cloud CDN / SPA
  "assets/audio",     // Audio MP3/WAV -> GCS CDN
]);

function copyRecursive(src, dest) {
  if (!fs.existsSync(src)) return;
  const stat = fs.statSync(src);
  if (stat.isDirectory()) {
    if (!fs.existsSync(dest)) fs.mkdirSync(dest, { recursive: true });
    for (const item of fs.readdirSync(src)) {
      copyRecursive(path.join(src, item), path.join(dest, item));
    }
  } else {
    fs.copyFileSync(src, dest);
  }
}

function prepareMobileAssets() {
  console.log("=== Memolandum Mobile Thin-Client Asset Sync ===");
  if (!fs.existsSync(OUT_DIR)) {
    throw new Error("out/ dizini bulunamadı. Lütfen önce slim build alın.");
  }

  // Ensure clean destination while preserving Capacitor/Cordova bridge files generated by `cap sync`
  const KEEP_BRIDGE_FILES = new Set(["cordova.js", "cordova_plugins.js", "plugins"]);
  if (fs.existsSync(ANDROID_PUBLIC_DIR)) {
    for (const existing of fs.readdirSync(ANDROID_PUBLIC_DIR)) {
      if (KEEP_BRIDGE_FILES.has(existing)) continue;
      fs.rmSync(path.join(ANDROID_PUBLIC_DIR, existing), { recursive: true, force: true });
    }
  } else {
    fs.mkdirSync(ANDROID_PUBLIC_DIR, { recursive: true });
  }

  let totalCopied = 0;
  for (const item of fs.readdirSync(OUT_DIR)) {
    if (EXCLUDE_NAMES.has(item)) {
      console.log(`⏩ [CDN Hariç Tutuldu]: ${item} (Sunucudan dinamik yüklenecek)`);
      continue;
    }

    const srcPath = path.join(OUT_DIR, item);
    const destPath = path.join(ANDROID_PUBLIC_DIR, item);

    // Special handling for assets folder: keep UI icons/sprites, exclude heavy audio/data
    if (item === "assets") {
      fs.mkdirSync(destPath, { recursive: true });
      for (const sub of fs.readdirSync(srcPath)) {
        if (sub === "audio" || sub.startsWith("_slim_skip")) {
          console.log(`⏩ [CDN Hariç Tutuldu]: assets/${sub} (GCS'den çalınacak)`);
          continue;
        }
        copyRecursive(path.join(srcPath, sub), path.join(destPath, sub));
      }
      continue;
    }

    // Special handling for sozluk: only copy _concept SPA shell if present
    if (item === "sozluk") {
      const conceptSrc = path.join(srcPath, "_concept");
      if (fs.existsSync(conceptSrc)) {
        copyRecursive(conceptSrc, path.join(destPath, "_concept"));
        console.log("✅ Sözlük SPA kabuğu eklendi: sozluk/_concept");
      }
      continue;
    }

    copyRecursive(srcPath, destPath);
    totalCopied++;
  }

  console.log("✅ Mobil Thin-Client varlıkları hazırlandı.");
}

prepareMobileAssets();
